// Builds what SenseGap customers download, into dist/:
//   collector → dist/sensegap-collector.js (the Cloudflare Worker, one file)
//   node      → packages/node/dist (the @sensegap/node package)
//   wordpress → collectors/wordpress/sensegap/includes/patterns.php + dist/sensegap-wordpress.zip
// Usage: node scripts/build.mjs [collector|node|wordpress ...]
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
mkdirSync(dist, { recursive: true });

const targets = process.argv.slice(2).length ? process.argv.slice(2) : ["collector", "node", "wordpress"];
const header = (what) => `// SenseGap ${what}. MIT licensed: https://github.com/tudortotolici/sensegap\n`;

async function collector() {
  const version = JSON.parse(readFileSync(join(root, "collectors/cloudflare/package.json"), "utf8")).version;
  await build({
    entryPoints: [join(root, "collectors/cloudflare/src/index.ts")],
    bundle: true, format: "esm", platform: "neutral", target: "es2022", minifySyntax: true, legalComments: "none",
    banner: { js: header(`Cloudflare collector ${version}`) },
    outfile: join(dist, "sensegap-collector.js"),
  });
  console.log(`collector ${version} → dist/sensegap-collector.js`);
}

async function node() {
  const pkg = join(root, "packages/node");
  rmSync(join(pkg, "dist"), { recursive: true, force: true });
  const common = { bundle: true, platform: "node", target: "node18", legalComments: "none", external: ["node:*"] };
  for (const format of ["esm", "cjs"]) {
    await build({ ...common, entryPoints: { index: join(pkg, "src/index.ts"), next: join(pkg, "src/next.ts") }, format, outdir: join(pkg, "dist"), outExtension: { ".js": format === "esm" ? ".js" : ".cjs" } });
  }
  await build({ ...common, entryPoints: [join(pkg, "src/cli.ts")], format: "esm", outfile: join(pkg, "dist/cli.js") });
  execFileSync(join(root, "node_modules/.bin/tsc"), ["-p", join(pkg, "tsconfig.build.json")], { stdio: "inherit" });
  console.log("node package → packages/node/dist");
}

async function wordpress() {
  // Same bot list as every other collector, as PHP regexes.
  const { BOTS, GENERIC_BOT, AI_REFERRERS } = await import(join(root, "packages/bots/src/index.ts"));
  const php = (re) => `'${("~" + re.source.replace(/~/g, "\\~") + "~" + (re.flags.includes("i") ? "i" : "")).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
  const ua = BOTS.filter((b) => b.ua).map((b) => `  ${php(b.ua)}, // ${b.name}`);
  const sig = BOTS.filter((b) => b.signatureAgentMatch).map((b) => `  ${php(b.signatureAgentMatch)},`);
  const hosts = [...new Set(AI_REFERRERS.flatMap((r) => r.hosts))];
  const plugin = join(root, "collectors/wordpress/sensegap");
  writeFileSync(
    join(plugin, "includes/patterns.php"),
    `<?php
// Generated by scripts/build.mjs from @sensegap/bots (${BOTS.length} bots). Do not edit.
if (!defined('ABSPATH')) exit;

const SENSEGAP_BOT_UA = [
${ua.join("\n")}
];
const SENSEGAP_SIGNATURE_AGENTS = [
${sig.join("\n")}
];
const SENSEGAP_GENERIC_BOT = ${php(GENERIC_BOT)};
const SENSEGAP_AI_HOSTS = [${hosts.map((h) => `'${h}'`).join(", ")}, 'chatgpt'];
`,
  );
  copyFileSync(join(root, "LICENSE"), join(plugin, "LICENSE"));
  rmSync(join(dist, "sensegap-wordpress.zip"), { force: true });
  execFileSync("zip", ["-r", "-X", "-q", join(dist, "sensegap-wordpress.zip"), "sensegap", "-x", "*.DS_Store"], { cwd: join(root, "collectors/wordpress") });
  console.log(`wordpress plugin: ${ua.length} bot patterns → dist/sensegap-wordpress.zip`);
}

const run = { collector, node, wordpress };
for (const t of targets) {
  if (!run[t]) throw new Error(`unknown target ${t}`);
  await run[t]();
}
